def make_cover_jpeg(width=600, height=900, title=BOOK_TITLE) -> bytes:
    """Simple synthetic cover art (gradient + lighthouse silhouette)."""
    img = Image.new("RGB", (width, height), (18, 26, 40))
    d = ImageDraw.Draw(img)
    for y in range(height):
        t = y / max(1, height - 1)
        d.line(
            [(0, y), (width, y)],
            fill=(int(18 + 60 * t), int(26 + 70 * t), int(40 + 95 * t)),
        )
    # sea band
    d.rectangle([0, int(height * 0.72), width, height], fill=(12, 30, 46))
    for i in range(6):
        y = int(height * 0.74) + i * 14
        d.line([(0, y), (width, y)], fill=(26 + i * 6, 58 + i * 8, 78 + i * 6))
    # beam
    d.polygon(
        [(width * 0.62, height * 0.30), (width, height * 0.20),
         (width, height * 0.40), (width * 0.62, height * 0.34)],
        fill=(250, 226, 150),
    )
    # tower
    tx, tw = int(width * 0.58), int(width * 0.10)
    d.polygon(
        [(tx - tw // 2, int(height * 0.66)), (tx + tw // 2, int(height * 0.66)),
         (tx + tw // 3, int(height * 0.34)), (tx - tw // 3, int(height * 0.34))],
        fill=(226, 226, 220),
    )
    d.rectangle([tx - tw // 2 - 6, int(height * 0.30), tx + tw // 2 + 6, int(height * 0.345)],
                fill=(198, 92, 70))
    d.rectangle([tx - 6, int(height * 0.62), tx + 6, int(height * 0.70)], fill=(150, 60, 48))
    for i, line in enumerate(textwrap.wrap(title, 22)[:3]):
        d.text((28, height - 120 + i * 20), line, fill=(236, 236, 230))
    d.text((28, height - 60), BOOK_AUTHOR, fill=(180, 190, 205))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=78, optimize=True)
    return buf.getvalue()


def make_comic_page(index: int, total: int, width=900, height=1350) -> bytes:
    """Synthetic comic page: panels, captions, balloons (no real artwork)."""
    img = Image.new("RGB", (width, height), (247, 245, 238))
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, width, 70], fill=(28, 32, 40))
    d.text((24, 26), "LIRUNE QA COMIC - PAGE %d OF %d" % (index, total),
           fill=(240, 240, 235))
    margin, gap = 40, 24
    panel_w = width - margin * 2
    panel_h = (height - 120 - margin - gap * 3) // 4
    palette = [
        ((222, 232, 240), (40, 60, 90)),
        ((238, 232, 214), (110, 80, 40)),
        ((226, 238, 226), (50, 90, 60)),
        ((238, 226, 232), (100, 50, 80)),
    ]
    for p in range(4):
        top = 90 + p * (panel_h + gap)
        bg, fg = palette[(index + p) % len(palette)]
        d.rectangle([margin, top, width - margin, top + panel_h], fill=bg, outline=fg, width=4)
        # simple panel content: horizon + shapes
        hz = top + int(panel_h * 0.62)
        d.line([(margin + 6, hz), (width - margin - 6, hz)], fill=fg, width=3)
        for k in range(3):
            cx = margin + 80 + k * 220 + (index * 17) % 60
            r = 30 + (index * 7 + k * 11) % 40
            d.ellipse([cx - r, hz - r - 10, cx + r, hz + r - 10], outline=fg, width=3)
        d.rectangle([margin + 6, top + 6, margin + 6 + 250, top + 6 + 24], fill=fg)
        d.text((margin + 12, top + 10), "PANEL %d.%d" % (index, p + 1), fill=(250, 250, 246))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=72, optimize=True)
    return buf.getvalue()


