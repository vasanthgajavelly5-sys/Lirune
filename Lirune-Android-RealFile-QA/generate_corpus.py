def qa_prose(seed: int = 0):
    """Return a deterministic prose block used by TXT/PDF/FB2/EPUB variants."""
    paras = []
    for ti, title in enumerate(CH_TITLES):
        paras.append(title)
        for p in CH_PARAS[(ti + seed) % len(CH_PARAS)]:
            paras.append(" ".join(textwrap.wrap(p, 78)))
    return paras


