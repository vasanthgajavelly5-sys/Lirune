def esc_pdf(text: str) -> bytes:
    out = text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
    return out.encode("latin-1", "replace")


class Pdf:
    """Minimal PDF 1.7 writer: Helvetica text pages, Info dict, XMP metadata."""

    def __init__(self):
        self.objects = [None]  # 1-based

    def add(self, payload: bytes) -> int:
        self.objects.append(payload)
        return len(self.objects) - 1

    def reserve(self) -> int:
        self.objects.append(b"")
        return len(self.objects) - 1

    def set(self, num: int, payload: bytes) -> None:
        self.objects[num] = payload

    def stream(self, dict_body: bytes, data: bytes) -> int:
        head = b"<< " + dict_body + b" /Length " + str(len(data)).encode() + b" >>\nstream\n"
        return self.add(head + data + b"\nendstream")

    def build(self, root: int, info: int, xmp: int | None = None) -> bytes:
        out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
        offsets = [0] * len(self.objects)
        for num in range(1, len(self.objects)):
            offsets[num] = len(out)
            out += str(num).encode() + b" 0 obj\n" + self.objects[num] + b"\nendobj\n"
        xref_pos = len(out)
        n = len(self.objects)
        out += b"xref\n0 " + str(n).encode() + b"\n"
        out += b"0000000000 65535 f \n"
        for num in range(1, n):
            out += ("%010d 00000 n \n" % offsets[num]).encode()
        out += (
            b"trailer\n<< /Size " + str(n).encode() + b" /Root " + str(root).encode()
            + b" 0 R /Info " + str(info).encode() + b" 0 R"
            + (b" /Metadata " + str(xmp).encode() + b" 0 R" if xmp else b"")
            + b" >>\nstartxref\n" + str(xref_pos).encode() + b"\n%%EOF\n"
        )
        return bytes(out)

    def text_page_obj(self, lines, font_num, font_size=11, leading=15, margin=60,
                      media=(0, 0, 612, 792)):
        """Create a page object whose content stream holds the given lines."""
        content = [b"BT", b"/F1 %d Tf" % font_size, b"%d TL" % leading,
                   b"1 0 0 1 %d %d Tm" % (margin, media[3] - 50)]
        cur_size = font_size
        for size, text in lines:
            if text == "":
                content.append(b"T*")
                continue
            if size != cur_size:
                content.append(b"/F1 %d Tf" % size)
                cur_size = size
            content.append(b"(" + esc_pdf(text) + b") Tj")
            content.append(b"T*")
        content.append(b"ET")
        stream = self.stream(b"", b"\n".join(content))
        res = (b"/Resources << /Font << /F1 " + str(font_num).encode()
               + b" 0 R >> /ProcSet [/PDF /Text] >>")
        page = self.reserve()
        self.set(
            page,
            b"<< /Type /Page /Parent 0 0 R /MediaBox ["
            + b" ".join(str(v).encode() for v in media)
            + b"] "
            + res
            + b" /Contents " + str(stream).encode() + b" 0 R >>",
        )
        return page

    def font(self):
        return self.add(
            b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
        )


def wrap_ascii(text: str, width: int = 92):
    return textwrap.wrap(text, width)


def build_pdf_text(path: str) -> None:
    pdf = Pdf()
    font = pdf.font()
    flat = qa_prose()
    chunk1 = flat[:8]
    chunk2 = flat[8:] or ["End of QA sample document."]

    def body_lines(chunks, start_with_heading=None):
        lines = []
        if start_with_heading:
            lines.append(start_with_heading)
            lines.append(("", ""))
        for para in chunks:
            if len(para) < 60 and para[:2].strip().rstrip(".").isdigit():
                lines.append((13, para))
                lines.append(("", ""))
            else:
                lines.extend((11, wl) for wl in wrap_ascii(para))
                lines.append(("", ""))
        return lines

    lines1 = (
        [(20, BOOK_TITLE), (12, "by " + BOOK_AUTHOR),
         (10, BOOK_SUBJECT + " - QA fixture"), ("", "")]
        + body_lines(chunk1)
    )
    lines2 = body_lines(chunk2)
    lines2.append((10, "End of document. Synthetic content for Lirune Reader QA only."))

    p1 = pdf.text_page_obj(lines1, font)
    p2 = pdf.text_page_obj(lines2, font)
    pages_obj = pdf.add(
        b"<< /Type /Pages /Kids [" + str(p1).encode() + b" 0 R " + str(p2).encode()
        + b" 0 R] /Count 2 >>"
    )
    for p in (p1, p2):
        pdf.set(p, pdf.objects[p].replace(b"/Parent 0 0 R", b"/Parent " + str(pages_obj).encode() + b" 0 R"))
    root = pdf.add(
        b"<< /Type /Catalog /Pages " + str(pages_obj).encode() + b" 0 R >>"
    )
    info = pdf.add(
        b"<< /Title (" + esc_pdf(BOOK_TITLE) + b") /Author (" + esc_pdf(BOOK_AUTHOR)
        + b") /Subject (" + esc_pdf(BOOK_SUBJECT) + b") /Creator (Lirune QA corpus generator)"
        b" /Producer (Lirune QA corpus generator) /Keywords (QA; pdf; sample)"
        b" /CreationDate (D:20260115093000Z) /ModDate (D:20260115093000Z) >>"
    )
    xmp = pdf.stream(
        b"/Type /Metadata /Subtype /XML", xmp_packet(BOOK_TITLE, BOOK_AUTHOR, BOOK_SUBJECT)
    )
    # attach the metadata stream to the catalog
    pdf.set(root, b"<< /Type /Catalog /Pages " + str(pages_obj).encode()
            + b" 0 R /Metadata " + str(xmp).encode() + b" 0 R >>")
    with open(path, "wb") as f:
        f.write(pdf.build(root, info, xmp))


