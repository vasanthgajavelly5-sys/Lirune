def build_mobi() -> bytes:
    text = (
        "The Lighthouse at Sker Point\r\n"
        "by A. Wren (QA Corpus)\r\n\r\n"
        "Synthetic MOBI/PDB stub used only to verify that Lirune Reader rejects"
        " the .mobi extension with a clear unsupported-format message. The text"
        " body is original placeholder prose written for Lirune QA.\r\n"
    ).encode("utf-8")

    name = b"LiruneQAUnsupportedSample"
    pad = name + b"\x00" * (32 - len(name))
    rec_count = 3
    header_len = 78
    record_info_len = 8 * rec_count
    rec0_off = header_len + record_info_len
    rec0 = b"\x01\x00\x00\x00" + struct.pack(">IHHH", len(text), 1, 4096, 0)  # PalmDOC
    rec0 = rec0.ljust(16, b"\x00")[:16]
    rec1_off = rec0_off + len(rec0)
    mobi_header = bytearray(232)
    mobi_header[0:4] = b"MOBI"
    struct.pack_into(">H", mobi_header, 4, 232)      # header length
    mobi_header[6] = 2                              # mobi type: book
    struct.pack_into(">I", mobi_header, 8, 0x54524541)  # unique id
    struct.pack_into(">I", mobi_header, 12, 6)      # file version
    struct.pack_into(">I", mobi_header, 20, len(text))   # first non-book index
    struct.pack_into(">I", mobi_header, 24, 0)      # full name offset
    struct.pack_into(">I", mobi_header, 28, 0)      # full name length
    struct.pack_into(">I", mobi_header, 36, 0)      # locale
    struct.pack_into(">I", mobi_header, 44, 0)      # input language
    struct.pack_into(">I", mobi_header, 48, 0)      # output language
    struct.pack_into(">I", mobi_header, 64, len(text))  # extra data 0 size
    struct.pack_into(">I", mobi_header, 84, 232)    # first image index
    rec1 = bytes(mobi_header)
    rec2_off = rec1_off + len(rec1)
    rec2 = text

    rec_infos = b"".join(
        struct.pack(">I", 0 if i == 0 else i) + struct.pack(">I", off)
        for i, off in enumerate((rec0_off, rec1_off, rec2_off))
    )
    header = bytearray(b"\x00" * header_len)
    header[0:32] = pad
    struct.pack_into(">HH", header, 32, 0, 0)            # attributes, version
    struct.pack_into(">III", header, 36, 0, 0, 0)        # creation, modification, backup dates
    struct.pack_into(">I", header, 48, 0)                 # modify number
    struct.pack_into(">II", header, 52, 0, 0)            # appinfo offset, sortinfo offset
    header[60:64] = b"BOOK"
    header[64:68] = b"TYPE"
    struct.pack_into(">I", header, 68, 0x12345678)       # unique id seed
    struct.pack_into(">I", header, 72, 2)                # next record list id
    struct.pack_into(">H", header, 76, rec_count)
    return bytes(header) + rec_infos + rec0 + rec1 + rec2


def _vint(value: int) -> bytes:
    out = bytearray()
    while True:
        b = value & 0x7F
        value >>= 7
        if value:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def _rar_header(htype: int, body: bytes) -> bytes:
    size_field = _vint(len(body) + 1)  # header type vint + body
    raw = size_field + _vint(htype) + body
    return struct.pack("<I", zlib.crc32(raw) & 0xFFFFFFFF) + raw


def build_rar5() -> bytes:
    signature = b"Rar!\x1a\x07\x01\x00"
    # main archive header (type 1)
    main = _rar_header(
        1,
        _vint(0)                      # archive flags
        + _vint(0)                    # volume number
        + _vint(0)                    # extra area size
        + b"\x00" * 8,                # reserved
    )
    payload = make_cover_jpeg(width=160, height=240)
    name = "cover.jpg".encode("utf-8")
    file_body = (
        _vint(0x0004)                 # file flags: data CRC32 present
        + _vint(len(payload))         # unpacked size
        + _vint(0x20)                 # attributes
        + struct.pack("<I", zlib.crc32(payload) & 0xFFFFFFFF)  # data CRC32
        + _vint(0)                    # compression info: version 0, method 0 (store)
        + _vint(0)                    # host OS: Windows
        + _vint(len(name))
        + name
    )
    file_hdr = _rar_header(2, file_body)
    eof = _rar_header(5, _vint(1))    # end of archive header
    return signature + main + file_hdr + payload + eof


