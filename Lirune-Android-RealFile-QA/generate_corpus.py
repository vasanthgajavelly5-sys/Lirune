def build_large_txt(path: str, target_bytes: int = 1_250_000) -> int:
    """Mixed-encoding UTF-8 text > 1 MB, built to stress chunkIndex.ts."""
    ascii_sentences = [
        "The keeper wrote the hour, the wind, and the number of ships that answered.",
        "Fog held the sound for four days and the light was not permitted to fail.",
        "Wick trimmed, lens polished, clock wound, log signed, lamp turned.",
        "A hull passed at two in the morning and signalled three short flashes.",
        "The road was under water, so the relief boat was three weeks late.",
        "Every entry in the ledger repeated itself until the pattern became a kind of calm.",
    ]
    cjk_lines = [
        "灯台の記録: 午前四時、水平線上に船影なし。",
        "灯塔守の手記 第二章 - 霧の中から見た光。",
        "第三章: ランプは消えない。",
        "第四章: 長い暗闇の期間、そして手拭いの重用。",
        "第五章: それでも灯りはここにある。",
    ]
    hangul = "第五条: 등대 기록 보관함의 온도 측정값."
    mixed_header = (
        "The Lighthouse at Sker Point\n"
        "by A. Wren (QA Corpus) - large TXT chunking fixture\n"
        + "=" * 78 + "\n"
        "This file is intentionally larger than 1 MB and mixes ASCII, CJK, and\n"
        "astral-plane emoji so that chunkIndex.ts chunk cutting, byte-offset\n"
        "mapping, and UTF-8 window reads are all exercised.\n"
        + "=" * 78 + "\n\n"
    )

    parts = [mixed_header]
    size = len(mixed_header.encode("utf-8"))
    chapter_no = 0
    while size < target_bytes:
        chapter_no += 1
        block = []
        block.append("CHAPTER %d\n" % chapter_no)
        block.append("-" * 78 + "\n")
        # plain paragraph lines
        for s in ascii_sentences:
            block.append(" ".join(textwrap.wrap(s, 78)) + "\n")
        # CJK / multilingual lines
        block.append(cjk_lines[chapter_no % len(cjk_lines)] + "\n")
        block.append(hangul + "\n")
        # emoji lines (4-byte UTF-8, surrogate pairs in JS)
        block.append(EMOJI_LINES[chapter_no % len(EMOJI_LINES)] + "\n")
        # indented lines to exercise space lookahead
        block.append("    indented note:  indented text with runs of spaces    inside\n")
        # long unbroken line (~6 KB) to exercise newline lookahead fallback
        block.append("LONG_LINE " + ("abcdefghij0123456789" * 340) + " END_LONG_LINE\n")
        # emoji-heavy long line
        block.append("EMOJI_RUN " + ("\U0001F525\U0001F30D\U0001F6F8 " * 60) + "\n")
        # CRLF line endings in this block only
        block.append("CRLF_BLOCK: this paragraph uses carriage-return line endings.\r\n")
        block.append("So does this one, and it contains CJK: 光の記録。\r\n")
        # line without trailing newline followed by next chapter (join hazard)
        if chapter_no % 5 == 0:
            block.append("NO_TRAILING_NEWLINE_MARKER_%d" % chapter_no)
        else:
            block.append(".\n")
        block.append("\n")
        text = "".join(block)
        parts.append(text)
        size += len(text.encode("utf-8"))
    data = "".join(parts).encode("utf-8")
    with open(path, "wb") as f:
        f.write(data)
    return len(data)


